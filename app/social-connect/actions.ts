/* ============================================================
   DELETE OWN POST
   ============================================================ */

export async function deletePost(
  formData: FormData,
) {
  const {
    supabase,
    user,
  } =
    await requireSocialProfile();


  const postId =
    String(
      formData.get(
        "post_id",
      ) ?? "",
    );


  if (!postId) {
    return;
  }


  const {
    data: post,
  } =
    await supabase
      .from(
        "social_posts",
      )
      .select(
        "id, user_id, media_path",
      )
      .eq(
        "id",
        postId,
      )
      .eq(
        "user_id",
        user.id,
      )
      .maybeSingle();


  if (!post) {
    return;
  }


  const {
    error,
  } =
    await supabase
      .from(
        "social_posts",
      )
      .delete()
      .eq(
        "id",
        postId,
      )
      .eq(
        "user_id",
        user.id,
      );


  if (
    !error &&
    post.media_path
  ) {
    await supabase.storage
      .from(
        "social-media",
      )
      .remove([
        post.media_path,
      ]);
  }


  redirect(
    "/social-connect",
  );
}



/* ============================================================
   FOLLOW / UNFOLLOW

   Follow notification handled by V8 DB trigger.
   ============================================================ */

export async function toggleFollow(
  formData: FormData,
) {
  const {
    supabase,
    user,
  } =
    await requireSocialProfile();


  const target =
    String(
      formData.get(
        "target_user_id",
      ) ?? "",
    );


  const username =
    String(
      formData.get(
        "username",
      ) ?? "",
    );


  if (
    !target ||
    target === user.id
  ) {
    return;
  }


  const {
    data:
      existing,
  } =
    await supabase
      .from(
        "social_follows",
      )
      .select(
        "follower_id",
      )
      .eq(
        "follower_id",
        user.id,
      )
      .eq(
        "following_id",
        target,
      )
      .maybeSingle();


  if (existing) {

    await supabase
      .from(
        "social_follows",
      )
      .delete()
      .eq(
        "follower_id",
        user.id,
      )
      .eq(
        "following_id",
        target,
      );


    await supabase
      .from(
        "social_notifications",
      )
      .delete()
      .eq(
        "actor_id",
        user.id,
      )
      .eq(
        "user_id",
        target,
      )
      .eq(
        "notification_type",
        "follow",
      );

  } else {

    await supabase
      .from(
        "social_follows",
      )
      .insert({
        follower_id:
          user.id,

        following_id:
          target,
      });
  }


  revalidatePath(
    `/social-connect/u/${username}`,
  );

  revalidatePath(
    "/social-connect",
  );
}



