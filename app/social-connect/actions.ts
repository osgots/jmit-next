"use server";

import {
  revalidatePath,
} from "next/cache";

import {
  redirect,
} from "next/navigation";

import {
  requireSocialProfile,
} from "@/lib/social/require-user";


function safePath(
  value:
    | FormDataEntryValue
    | null,
) {
  const path =
    String(
      value ?? "",
    );

  if (
    path.startsWith("/") &&
    !path.startsWith("//")
  ) {
    return path;
  }

  return "/social-connect";
}


/* ============================================================
   LIKE / UNLIKE

   Notification itself is generated by PostgreSQL V8 trigger.
   ============================================================ */

export async function toggleLike(
  formData: FormData,
) {
  const {
    supabase,
    user,
  } =
    await requireSocialProfile();


  const postId =
    String(
      formData.get(
        "post_id",
      ) ?? "",
    );


  const returnTo =
    safePath(
      formData.get(
        "return_to",
      ),
    );


  if (!postId) {
    return;
  }


  const {
    data:
      existing,
  } =
    await supabase
      .from(
        "social_likes",
      )
      .select(
        "post_id",
      )
      .eq(
        "post_id",
        postId,
      )
      .eq(
        "user_id",
        user.id,
      )
      .maybeSingle();


  if (existing) {

    await supabase
      .from(
        "social_likes",
      )
      .delete()
      .eq(
        "post_id",
        postId,
      )
      .eq(
        "user_id",
        user.id,
      );


    /*
     * Remove the old like notification too.
     */
    await supabase
      .from(
        "social_notifications",
      )
      .delete()
      .eq(
        "actor_id",
        user.id,
      )
      .eq(
        "notification_type",
        "like",
      )
      .eq(
        "entity_id",
        postId,
      );

  } else {

    await supabase
      .from(
        "social_likes",
      )
      .insert({
        post_id:
          postId,

        user_id:
          user.id,
      });
  }


  revalidatePath(
    returnTo,
  );

  revalidatePath(
    "/social-connect",
  );
}



