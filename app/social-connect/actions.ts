/* ============================================================
   COMMENT
   ============================================================ */

export async function addComment(
  formData: FormData,
) {
  const {
    supabase,
    user,
  } =
    await requireSocialProfile();


  const postId =
    String(
      formData.get(
        "post_id",
      ) ?? "",
    );


  const body =
    String(
      formData.get(
        "body",
      ) ?? "",
    ).trim();


  const returnTo =
    safePath(
      formData.get(
        "return_to",
      ),
    );


  if (
    !postId ||
    body.length < 1 ||
    body.length > 1000
  ) {
    return;
  }


  const {
    error,
  } =
    await supabase
      .from(
        "social_comments",
      )
      .insert({
        post_id:
          postId,

        user_id:
          user.id,

        body,
      });


  /*
   * Comment + mention notifications
   * are generated by PostgreSQL triggers.
   */


  revalidatePath(
    returnTo,
  );

  revalidatePath(
    "/social-connect",
  );
}



/* ============================================================
   EDIT OWN COMMENT
   ============================================================ */

export async function editComment(
  formData: FormData,
) {
  const {
    supabase,
    user,
  } =
    await requireSocialProfile();


  const commentId =
    String(
      formData.get(
        "comment_id",
      ) ?? "",
    );


  const body =
    String(
      formData.get(
        "body",
      ) ?? "",
    ).trim();


  const returnTo =
    safePath(
      formData.get(
        "return_to",
      ),
    );


  if (
    !commentId ||
    body.length < 1 ||
    body.length > 1000
  ) {
    return;
  }


  /*
   * ONLY comment author may edit.
   */
  await supabase
    .from(
      "social_comments",
    )
    .update({
      body,

      updated_at:
        new Date()
          .toISOString(),
    })
    .eq(
      "id",
      commentId,
    )
    .eq(
      "user_id",
      user.id,
    );


  revalidatePath(
    returnTo,
  );
}



