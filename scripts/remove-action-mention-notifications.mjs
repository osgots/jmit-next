import fs from "node:fs";

const file =
  "app/social-connect/actions.ts";

let code =
  fs.readFileSync(
    file,
    "utf8",
  );

const start =
`  /*
   * Comment notification is handled
   * automatically by V8 DB trigger.
   */
  if (!error) {`;

const end =
`
  revalidatePath(
    returnTo,
  );`;

const startIndex =
  code.indexOf(
    start,
  );

if (
  startIndex === -1
) {
  console.log(
    "Mention action block already removed or changed.",
  );

  process.exit(0);
}

const endIndex =
  code.indexOf(
    end,
    startIndex,
  );

if (
  endIndex === -1
) {
  console.error(
    "Could not locate end of mention notification block.",
  );

  process.exit(1);
}

code =
  code.slice(
    0,
    startIndex,
  ) +
`  /*
   * Comment + mention notifications
   * are generated by PostgreSQL triggers.
   */

` +
  code.slice(
    endIndex,
  );


fs.writeFileSync(
  file,
  code,
  "utf8",
);

console.log(
  "✓ Duplicate client-side mention notifications removed.",
);
